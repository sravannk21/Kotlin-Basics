package com.learn.kotlinbasics

fun main(){
    var circleRatio=3.14;
    println(circleRatio);
    circleRatio=3.1415926535897932;
    println(circleRatio);

    //declaring float by manually because kotlin default taken as double
    var circleRATIO=3.14f;
    println(circleRATIO)
    circleRATIO=3.1415926535f
    println(circleRATIO)
}